#!/usr/bin/env python3
"""Regenerate docs/DISH-RECONCILIATION.md from the live data files.

Keeps the reconciliation document honest: it is always derived from
src/data/dishCatalog.json and src/data/photography.json, never hand-edited.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOGUE = json.loads((ROOT / "src/data/dishCatalog.json").read_text(encoding="utf-8"))
PHOTO = json.loads((ROOT / "src/data/photography.json").read_text(encoding="utf-8"))
OUT = ROOT / "docs/DISH-RECONCILIATION.md"

TERRITORIES = [
    "Delhi",
    "Jammu and Kashmir",
    "Ladakh",
    "Andaman and Nicobar Islands",
    "Puducherry",
]
EXCLUDED = [
    "Chandigarh",
    "Lakshadweep",
    "Dadra and Nagar Haveli and Daman and Diu",
]

by_id = {d["id"]: d for d in CATALOGUE["dishes"]}


def dish_cell(dish_id: str) -> str:
    dish = by_id[dish_id]
    record = PHOTO["dishes"].get(dish_id, {})
    has_plate = bool(record.get("plated"))
    has_stages = sum(
        1
        for key in ("origin", "ingredients", "method", "plated")
        if (record.get(key) if key == "plated" else (record.get(key) or {}).get("photo"))
    )
    flag = "" if has_plate else " ⚠︎"
    return f"{dish['name']}{flag} ({has_stages}/4 stages)"


lines: list[str] = []
add = lines.append
add("# Dish reconciliation — actual repo state vs the 94-item target")
add("")
add(
    "Generated by `scripts/generate-dish-reconciliation.py` from "
    "`src/data/dishCatalog.json` and `src/data/photography.json`. "
    f"**{CATALOGUE['totalDishes']} dishes across {len(CATALOGUE['groups'])} groups** are present."
)
add("")
add("Target: 28 states × 3 dishes = 84, plus 5 union territories × 2 dishes = 10, **94 total**.")
add("")
add(
    "⚠︎ = the dish exists but has no verified finished-dish photograph. "
    "`n/4 stages` counts the verified, individually credited photographs for that dish."
)
add("")
add("## States (28) — three dishes each, target met")
add("")
add("| State | Dishes | Count | Target |")
add("|---|---|---:|---:|")
for group in CATALOGUE["groups"]:
    if group["classification"] != "State":
        continue
    add(
        f"| {group['state']} | " +
        "; ".join(dish_cell(did) for did in group["dishIds"]) +
        f" | {len(group['dishIds'])} | 3 |"
    )
add("")
add("## Union territories (5) — two dishes each, target met")
add("")
add("| Union Territory | Dishes | Count | Target |")
add("|---|---|---:|---:|")
for group in CATALOGUE["groups"]:
    if group["classification"] != "Union Territory":
        continue
    add(
        f"| {group['state']} | " +
        "; ".join(dish_cell(did) for did in group["dishIds"]) +
        f" | {len(group['dishIds'])} | 2 |"
    )
add("")
add("## Scope boundaries")
add("")
add("The following union territories are deliberately **not** in the collection, per the brief:")
for name in EXCLUDED:
    add(f"* {name} — excluded, not added")
add("")
add("Retained union territories: " + ", ".join(TERRITORIES) + ".")
add("")

plated = sum(1 for record in PHOTO["dishes"].values() if record.get("plated"))
assignments = sum(
    1
    for record in PHOTO["dishes"].values()
    for key in ("origin", "ingredients", "method", "plated")
    if (record.get(key) if key == "plated" else (record.get(key) or {}).get("photo"))
)
add("## Photographic status")
add("")
add(f"* Dishes with a verified finished-dish photograph: **{plated} of {CATALOGUE['totalDishes']}**.")
add(
    f"* Verified stage photographs: **{assignments} of {CATALOGUE['totalDishes'] * 4}**. "
    "Unverified stages render as explicitly unresolved frames — no borrowed or generated image."
)
add("* Full photographer, licence and source ledger: [`../PHOTOGRAPHY-CREDITS.md`](../PHOTOGRAPHY-CREDITS.md).")
add("")
add("## Integrity check")
add("")
add("`npm run atlas:check` validates the 94/28×3/5×2 counts, unique IDs, regional associations,")
add("the 376 four-stage histories, the four data-driven timeline waypoints per dish, the seven")
add("3D Studio stages, every photo credit and every local WebP file.")
add("")

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {OUT.relative_to(ROOT)} — {CATALOGUE['totalDishes']} dishes, {plated} plated")
